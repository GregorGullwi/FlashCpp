param(
	[Parameter(Mandatory = $true)]
	[string]$OutputPath,
	[int]$Seed = 20260824,
	[int]$FunctionCount = 1000
)

$ErrorActionPreference = "Stop"

$resolvedOutput = [System.IO.Path]::GetFullPath($OutputPath)
$outputDirectory = [System.IO.Path]::GetDirectoryName($resolvedOutput)
[System.IO.Directory]::CreateDirectory($outputDirectory) | Out-Null

$random = [System.Random]::new($Seed)
$source = [System.Text.StringBuilder]::new()
[void]$source.AppendLine("// Generated by generate_parallel_frontend_large.ps1; seed=$Seed")
[void]$source.AppendLine("template <class T> constexpr T mix_value(T value, T salt) {")
[void]$source.AppendLine("`treturn (value * T{33}) ^ (salt + T{17});")
[void]$source.AppendLine("}")
[void]$source.AppendLine("struct CorpusRecord { int a; long long b; unsigned c; };")
# Logical-depth stress is a separate correctness workload because the current
# recursive class-template path overflows the native stack.
[void]$source.AppendLine("constexpr int corpus_constant = mix_value(11, 7);")

for ($index = 0; $index -lt $FunctionCount; ++$index) {
	$constant = $random.Next(1, 1000000)
	$prior = if ($index -eq 0) { "corpus_constant" } else { "independent_$($index - 1)($constant & 255)" }
	[void]$source.AppendLine("int independent_$index(int value) {")
	[void]$source.AppendLine("`tCorpusRecord record{value, static_cast<long long>(value) * $constant, static_cast<unsigned>($constant)};")
	[void]$source.AppendLine("`tauto local = mix_value(record.a + static_cast<int>(record.c & 31u), $constant);")
	[void]$source.AppendLine("`treturn (local ^ static_cast<int>(record.b)) + ($prior & 7);")
	[void]$source.AppendLine("}")
}

[void]$source.AppendLine("int main() {")
[void]$source.AppendLine("`tint result = 0;")
$stride = [Math]::Max(1, [int]($FunctionCount / 64))
for ($index = 0; $index -lt $FunctionCount; $index += $stride) {
	[void]$source.AppendLine("`tresult ^= independent_$index($index);")
}
[void]$source.AppendLine("`treturn result & 255;")
[void]$source.AppendLine("}")

[System.IO.File]::WriteAllText($resolvedOutput, $source.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output $resolvedOutput
